export const MESSAGES: Record<Locale, Record<MessageKey, string>> = { de, en }

export function createTranslator(locale: Locale) {
  const table = MESSAGES[locale] ?? MESSAGES.de
  return (key: MessageKey, vars: Record<string, string | number> = {}): string =>
    table[key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`))
}

export type Translator = ReturnType<typeof createTranslator>
