// Compiles packages/designer/src/theme.css (Tailwind v4, authored with @apply) into a plain CSS string module.
// The Designer injects that string at runtime, so host apps need no Tailwind and no CSS import.
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'

const root = new URL('../packages/designer/', import.meta.url).pathname
const require = createRequire(root)
const cli = join(dirname(require.resolve('@tailwindcss/cli/package.json')), 'dist', 'index.mjs')
const css = execFileSync('node', [cli, '-i', join(root, 'src/theme.css'), '--minify'], { encoding: 'utf8', maxBuffer: 16 * 1024 * 1024 }).trim()
if (!css.includes('.pld-root')) throw new Error('Tailwind produced no Designer styles')
const target = join(root, 'src/styles.generated.ts')
const output = `// Generated by scripts/build-styles.mjs from src/theme.css. Do not edit.\nexport const CSS = ${JSON.stringify(css)}\n`
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) {
    console.error('styles.generated.ts is out of date: run `node scripts/build-styles.mjs`')
    process.exit(1)
  }
  console.log('styles.generated.ts is up to date')
} else {
  writeFileSync(target, output)
  console.log(`styles.generated.ts written (${(css.length / 1024).toFixed(1)} KB)`)
}
