// Generates the bundled Roboto font module (Apache-2.0) from the files shipped with pdfmake.
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'

const require = createRequire(new URL('../packages/core/package.json', import.meta.url))
const dir = join(dirname(require.resolve('pdfmake/package.json')), 'fonts', 'Roboto')
const files = {
  normal: 'Roboto-Regular.ttf',
  bold: 'Roboto-Medium.ttf',
  italics: 'Roboto-Italic.ttf',
  bolditalics: 'Roboto-MediumItalic.ttf',
}
let out = '// Generated by scripts/gen-roboto.mjs. Do not edit.\nexport const ROBOTO_BASE64: Record<"normal" | "bold" | "italics" | "bolditalics", string> = {\n'
for (const [style, file] of Object.entries(files)) {
  out += `  ${style}: "${readFileSync(join(dir, file)).toString('base64')}",\n`
}
out += '}\n'
writeFileSync(new URL('../packages/core/src/fonts/roboto-data.ts', import.meta.url), out)
console.log('roboto-data.ts written')
